def rate_metrics(df):
    df=df.copy()
    df["点赞率"] = df["点赞数"] / df["播放量"]
    df["投币率"] = df["投币数"] / df["播放量"]
    df["收藏率"] = df["收藏数"] / df["播放量"]
    df["弹幕率"] = df["弹幕数"] / df["播放量"]
    #df["评论率"] = df["评论数"] / df["播放量"]
    #df["分享率"] = df["分享数"] / df["播放量"]
    #df["转发率"] = df["转发数"] / df["播放量"]
    #df["关注率"] = df["关注数"] / df["播放量"]
    df["综合互动率"] = (df["点赞数"] + df["投币数"] + df["收藏数"] + df["弹幕数"]) / df["播放量"]
    return df
